import { SupportedLanguage, GameInfo } from '../types';

export const LANGUAGE_STORAGE_KEY = 'famplay_language';

export const getStoredLanguage = (): SupportedLanguage => {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY) as SupportedLanguage;
    if (saved && ['en', 'de', 'es', 'fr', 'it', 'ja'].includes(saved)) {
      return saved;
    }
    const nav = (typeof navigator !== 'undefined' ? navigator.language : '').toLowerCase();
    if (nav.startsWith('de')) return 'de';
    if (nav.startsWith('es')) return 'es';
    if (nav.startsWith('fr')) return 'fr';
    if (nav.startsWith('it')) return 'it';
    if (nav.startsWith('ja')) return 'ja';
  } catch {
    // fallback if localStorage not accessible
  }
  return 'de';
};

export const setStoredLanguage = (lang: SupportedLanguage) => {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new Event('famplay_language_changed'));
    }
  } catch {
    // ignore storage quota/privacy issues
  }
};

