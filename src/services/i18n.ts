export const getLocalizedGame = (game: GameInfo, lang: SupportedLanguage): GameInfo => {
  const loc = GAME_LOCALIZATIONS[game.id]?.[lang];
  if (!loc) return game;
  return {
    ...game,
    title: loc.title || game.title,
    description: loc.description || game.description,
    rulesSummary: loc.rulesSummary || game.rulesSummary,
    players: loc.players || game.players,
  };
};
