export const getTranslation = (lang: SupportedLanguage, key: string, params?: Record<string, string | number>): string => {
  let str = translations[lang]?.[key] || translations.de[key] || translations.en[key] || key;
  if (params) {
    Object.entries(params).forEach(([pKey, pVal]) => {
      str = str.replace(new RegExp(`\\{${pKey}\\}`, 'g'), String(pVal));
    });
  }
  return str;
};

